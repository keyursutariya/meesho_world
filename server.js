/* ================================================================
   MEESHO WORLD — server.js
   Zero-dependency Node HTTP server.
   Reads .env and dynamically serves /config.js with real values.
================================================================ */

const http = require('http');
const fs   = require('fs');
const path = require('path');

/* ── Load .env if present ────────────────────────────────── */
(function loadEnv() {
  const envPath = path.join(__dirname, '.env');
  if (!fs.existsSync(envPath)) return;
  const lines = fs.readFileSync(envPath, 'utf8').split('\n');
  lines.forEach(line => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const eq = trimmed.indexOf('=');
    if (eq < 0) return;
    const key = trimmed.slice(0, eq).trim();
    const val = trimmed.slice(eq + 1).trim();
    if (!process.env[key]) process.env[key] = val;
  });
})();

/* ── Build config.js content from env vars ───────────────── */
function buildConfigJs() {
  const cfg = {
    META_PIXEL_ID:    process.env.META_PIXEL_ID    || '1511058947312930',
    UPI_VPA:          process.env.UPI_VPA           || 'paytm.s3vx0km@pty',
    PAYEE_NAME:       process.env.PAYEE_NAME        || 'Kumbhani Mamataben Nareshbhai',
    TRANSACTION_NOTE: process.env.TRANSACTION_NOTE  || 'Verified Paytm Merchant',
    PRICE_1PC:        Number(process.env.PRICE_1PC) || 299,
    PRICE_2PC:        Number(process.env.PRICE_2PC) || 499,
    PRICE_3PC:        Number(process.env.PRICE_3PC) || 799,
    MRP_1PC:          Number(process.env.MRP_1PC)   || 1499,
    MRP_2PC:          Number(process.env.MRP_2PC)   || 2499,
    MRP_3PC:          Number(process.env.MRP_3PC)   || 3999,
  };

  return `/* AUTO-GENERATED by server.js from .env — do not edit manually */\nwindow.APP_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`;
}

const PORT = process.env.PORT || 3000;
const ROOT = __dirname;

const MIME_TYPES = {
  '.html': 'text/html; charset=UTF-8',
  '.js':   'application/javascript; charset=UTF-8',
  '.css':  'text/css; charset=UTF-8',
  '.json': 'application/json; charset=UTF-8',
  '.png':  'image/png',
  '.jpg':  'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.svg':  'image/svg+xml',
  '.ico':  'image/x-icon',
  '.gif':  'image/gif',
  '.woff': 'font/woff',
  '.woff2':'font/woff2',
  '.ttf':  'font/ttf',
};

const server = http.createServer((req, res) => {
  try {
    const parsedUrl = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
    let pathname = decodeURIComponent(parsedUrl.pathname);

    /* ── Serve /config.js dynamically from env ─────────── */
    if (pathname === '/config.js' || pathname.endsWith('/config.js')) {
      const content = buildConfigJs();
      res.writeHead(200, {
        'Content-Type': 'application/javascript; charset=UTF-8',
        'Cache-Control': 'no-store',
      });
      res.end(content);
      return;
    }

    // Root URL
    if (pathname === '/' || pathname === '') pathname = '/index.html';

    const safePath = path.normalize(pathname).replace(/^(\.\.[\\/])+/, '');
    let filePath = path.join(ROOT, safePath);
    let finalPath = null;

    // 1. Direct file check
    if (fs.existsSync(filePath) && fs.statSync(filePath).isFile()) {
      finalPath = filePath;
    }
    // 2. Add .html extension (e.g. /product → product.html)
    else if (fs.existsSync(filePath + '.html') && fs.statSync(filePath + '.html').isFile()) {
      finalPath = filePath + '.html';
    }
    // 3. Product detail routes /product/:id or /product
    else if (pathname.startsWith('/product/') || pathname === '/product') {
      const prodHtml = path.join(ROOT, 'product.html');
      if (fs.existsSync(prodHtml)) finalPath = prodHtml;
    }
    // 4. Directory with index.html
    else if (fs.existsSync(filePath) && fs.statSync(filePath).isDirectory()) {
      const idxHtml = path.join(filePath, 'index.html');
      if (fs.existsSync(idxHtml)) finalPath = idxHtml;
    }

    // 5. SPA fallback for extensionless paths
    if (!finalPath) {
      if (!path.extname(pathname)) {
        const fallback = path.join(ROOT, 'index.html');
        if (fs.existsSync(fallback)) finalPath = fallback;
      }
    }

    if (!finalPath) {
      res.writeHead(404, { 'Content-Type': 'text/html; charset=UTF-8' });
      res.end(`<!DOCTYPE html><html><head><title>404</title></head><body style="font-family:sans-serif;text-align:center;padding:50px"><h1>404 - Page Not Found</h1><a href="/" style="color:#9f2089;font-weight:bold;text-decoration:none">Return to Meesho Home</a></body></html>`);
      return;
    }

    const ext = path.extname(finalPath).toLowerCase();
    const contentType = MIME_TYPES[ext] || 'application/octet-stream';
    res.writeHead(200, {
      'Content-Type': contentType,
      'Cache-Control': 'no-cache',
      'Access-Control-Allow-Origin': '*',
    });
    fs.createReadStream(finalPath).pipe(res);
  } catch (err) {
    res.writeHead(500, { 'Content-Type': 'text/plain; charset=UTF-8' });
    res.end('Server Error: ' + err.message);
  }
});

server.listen(PORT, () => {
  console.log(`\n✅  Meesho store running → http://localhost:${PORT}`);
  console.log(`📋  Config served from .env → http://localhost:${PORT}/config.js`);
  console.log(`📊  Tracking dashboard → http://localhost:${PORT}/track-dashboard\n`);
  console.log('Press Ctrl+C to stop.\n');
});
